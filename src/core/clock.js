// 하루의 셈 — **없앴다.**
//
// 선생님(2026-09-26, 화면을 찍어 보내시며):
//   「해 칸을 다 써버려서 제대로 된 역사학습이 이뤄지지 않아.
//    해 칸 없애버리고 나머지 미션 수행하지 못하면 못넘어가게 해야해」
//
// 찍어 보내신 화면에는 이렇게 적혀 있었다 —
//   하지 않은 일 2
//     최익현의 상소를 듣는다   해 칸을 다 씀
//     수군 관원에게 말을 건다   해 칸을 다 씀
//
// **1876년 최익현의 상소를 못 본 채로 3막이 끝난 것이다.** 그것은 이 수업의 내용이다.
// 「무엇을 포기했는가」를 가르치려고 둔 장치가, 정작 가르쳐야 할 역사를 학생에게서
// 빼앗고 있었다. 장치가 목적을 이겼으면 장치를 버린다.
//
// 그래서 값은 0 이 된다. 문서를 읽든 신하의 말을 듣든 궁 밖에 나가든 치를 것이 없다.
// 대신 **다 하기 전에는 그 하루를 나갈 수 없다**(systems/freedom.js 의 exitBlock).
// 고르는 대신 다 한다 — 포기는 이제 학생의 선택이 아니라 역사가 막은 자리(조작권·
// 봉쇄)에서만 생긴다.
//
// ── 옛 모델(2026-09-13 ~ 09-25) ──────────────────────────────────────────
// 한때 이 파일은 「임금이 하루에 몇 사람의 아룀을 들을 수 있는가」를 셈했다. 그전에는
// 「남은 해」였고(방마다 1~4칸), 선생님이 그것을 끝냈다:
//   "남은 해와 이벤트로 해가 나오는 형태가 어디있어, 어전회의에 맞지 않아."
// 두 모델 다 같은 곳에서 무너졌다 — 학생이 역사를 만나기 전에 자원이 먼저 떨어진다.
//
// 이름은 남겨 둔다. spend()·costOf() 를 부르는 자리가 게임 곳곳에 있고, 그 자리들이
// 하는 일(값을 치른 뒤에 화면을 연다)은 그대로 옳기 때문이다. 값이 0 일 뿐이다.

// 한 번 듣는 데 드는 값 — 이제 없다.
export const AUDIENCE_COST = 0

// 남은 칸을 화면에 그리지 않는다(ui/hud.js). 하루의 길이라는 것이 없다.
export const DAY_UNITS = 0

export function costOf() {
  return AUDIENCE_COST
}

export function costOfPlaces() {
  return AUDIENCE_COST
}

// 언제나 치를 수 있다. 부르는 쪽의 「값을 치른 뒤에 연다」는 순서를 깨지 않으려고
// 모양을 그대로 둔다 — { ok, state } 다.
export function spend(state) {
  return { ok: true, state }
}

// 해는 지지 않는다. 하루를 끝내는 것은 이제 「할 일을 다 했는가」다(freedom.exitBlock).
export function isDusk() {
  return false
}

export function newDay(state) {
  return state
}
