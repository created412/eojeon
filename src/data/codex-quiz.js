// 막 하나의 질문. 막 id('yangyo')로도, 막 번호(2)로도 찾는다 — 부르는 쪽이 어느
// 쪽을 들고 있든(acts.js 의 act.id / state.actIndex+1) 한 줄로 끝나게 한다.
export function quizFor(act) {
  if (act == null) return null
  if (typeof act === 'number') {
    return Object.values(CODEX_QUIZZES).find(q => q.act === act) ?? null
  }
  return CODEX_QUIZZES[act] ?? null
}
