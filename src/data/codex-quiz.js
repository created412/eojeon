// 자리다.」
//
// 왜 이 파일이 필요한가: 지금까지 사초함은 **쌓이기만 했다.** 학생은 신하에게 걸어가
// 문서를 받고, 읽고, 목록에 한 줄이 늘어나는 것을 본다. 그런데 그 문서를 쓰는 자리가
// 게임 어디에도 없었다 — 어전회의의 선택지가 requires 로 문서를 요구하지만, 그것은
// 「고를 수 있게 된다」일 뿐 「그 문서에 적힌 말로 대답한다」가 아니다. 그래서 모으는
// 일이 심부름처럼 느껴졌다. 이 질문이 그 자리다.
//
// ── 이 파일이 지키는 규칙 셋 ──────────────────────────────────────────────
// ① wants 에 적는 id 는 **그 막에서 실제로 손에 들어오는 문서**여야 한다. 손으로 적는
//    목록이라 언제든 조용히 거짓이 될 수 있다 — 막이 하나 늘거나, 신하가 서는 막이
//    바뀌거나, 카드 하나가 다음 막으로 밀리면 그렇다. tests/systems/codex-quiz.test.js
//    가 acts.js·npcs.js 를 직접 훑어 「그 막에서 정말 받을 수 있는가」를 붙든다.
//    이 파일을 고치기 전에 그 시험을 먼저 읽을 것.
// ② explain 은 **카드가 실제로 말하는 것만** 말한다. 카드의 excerpt·origin·meaning 이
//    받쳐 주지 않는 문장은 한 줄도 적지 않는다. 학생이 「내가 고른 문서 옆에 뜬 해설」을
//    읽고 그 문서로 돌아갔을 때, 거기 없는 말이 해설에 있으면 그것이 이 게임이
//    가르치는 가장 나쁜 것이 된다.
// ③ origin 은 「그 문서가 어디에 있었는가」만 적는다. 「왜 안 주웠느냐」가 아니다.
//    안 모은 학생이 읽을 유일한 줄이라, 이 문장의 말투가 곧 이 화면의 말투다.
//    「…에 있었다」로 끝낸다 — 사실 하나를 놓고 판정을 붙이지 않는다.
//
