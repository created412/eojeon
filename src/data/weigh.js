// 임금의 저울 — 문을 열 것인가(1876년 음력 1월).
//
// 선생님(2026-10-06): 「나라의 문을 여는 문호개방에 대하여 대원군이 물러난 뒤에 신하들의 의견을
// 듣고 고종이 치열하게 고민하는 장면을 교육적인 게임으로 적용하고 싶어. 이 고민이 정말 게임의
// 백미가 되었으면 좋겠어.」
//
// 그래서 이 판은 지어낸 말로 짓지 않았다. 『고종실록』 13년 1월 20일~27일의 기록을 그대로 쓴다.
// 읽어 보니 기록이 이미 한 편의 이야기였다:
//
//   1월 20일  임금이 대신 여섯을 불러 묻는다. 여섯이 말한다 — 「헤아리기 어렵다」「날마다 모여
//             의논하고 있다」「보고를 기다려서」. **받아들이자는 사람도, 물리치자는 사람도 없다.**
//             교과서가 통상 개화론자로 꼽는 박규수조차 이날 남긴 말은 「분함을 금치 못하겠다」다.
//   1월 21일  강화도에서 보고가 온다. 일본 사신이 말했다 — 「우리 군사들이 상륙할 염려가 있다.」
//   1월 23일  최익현이 도끼를 지고 엎드린다. 나라가 망하는 까닭 다섯 가지.
//   1월 24일  의정부가 아뢴다. 「300년 … 반드시 통상을 거절할 필요는 없습니다.」
//   1월 27일  임금의 전교. 「일본을 제어하는 일은 일본을 제어하는 일이고, 서양을 배척하는 일은
//             서양을 배척하는 일이다.」 최익현은 그날로 흑산도로 간다.
//
// 그리고 한 가지를 알게 되었다: 교과서 110쪽이 「개항을 둘러싼 논란 — 찬성」으로 실은 글
// (『승정원일기』)이 바로 이 1월 27일의 전교다. **찬성의 한가운데에 임금 자신이 있었다.**
// 이 판은 그 사실을 끝에서 연다.
//
// ── 판의 꼴 ──────────────────────────────────────────────────────────────
// 답을 주는 신하가 없으니, 정하는 것은 임금이다. 들은 말과 겪은 일이 추가 되어 하나씩 온다.
// 추마다 **읽는 길이 둘**이다 — 같은 말이 닫는 쪽에도, 여는 쪽에도 오를 수 있다(구로다의 으름장은
// 「그러니 받아야 한다」도 되고 「그런 자와는 맺을 수 없다」도 된다). 어느 쪽에, 얼마나 무겁게
// 올릴지는 학생이 읽고 정한다. 맞는 답이 없다. 저울이 기운 뒤에도 정하는 것은 학생이다.
//
// 끝에서 실제의 일이 저울 위에서 벌어진다: 임금이 「왜와 양은 하나」라는 추를 내리고, 최익현이
// 섬으로 가며 그의 추가 함께 떠나고, 조약의 도장이 여는 쪽에 내려앉는다.
//
// ── 뒷날의 눈 ────────────────────────────────────────────────────────────
// 학생은 바로 앞 판에서 조약문을 뜯어 읽었다. 그 풀이(영사 재판권·해안 측량이 무엇을 불러왔는가)는
// 1876년의 어전에 없던 것이다. 그래서 마지막 추는 빛깔이 다르다 — 올려도 되고 내려놓아도 된다.
// 올렸다면 「실제로는」에서 그 추가 걷힌다. 뒷날의 눈으로 그때의 결정을 재는 일이 무엇인지를
// 저울이 보여 준다.
//
// ── 지어낸 것과 아닌 것 ───────────────────────────────────────────────────
//   기록      대신 여섯의 말 · 구로다의 말 · 최익현의 상소 · 의정부의 계 · 임금의 전교
//             (『고종실록』 13년 1월 20·21·23·24·27일 · 국사편찬위원회 우리말 옮김에서 줄여 실음)
//   교과서    「논의 끝에 개항을 결정하고 … 강화도 조약을 맺었다(1876)」, 「최초의 근대적 조약이자
//             불평등 조약」(110~111쪽)
//   재구성    읽는 길 두 가지(추마다) · 「강화도」「아버지의 돌」 추 — 임금이 그렇게 떠올렸다는
//             기록은 없다. 화면이 「당신이 지나온 일」이라고 밝힌다.
//
// 적는 법
//   ministers  1월 20일의 여섯. line 은 실록의 말을 줄인 것(…은 줄인 자리).
//   ask        다 듣고 나서 묻는 하나 — 읽지 않고는 넘어가지 못한다.
//   weights    추. tag 는 이름, mark 는 추의 몸에 새기는 짧은 이름(없으면 tag). readings 는 둘. side: 'shut'(닫는 쪽) · 'open'(여는 쪽) · 'none'(올리지 않는다).
//              hindsight:true 는 뒷날의 눈.
//   actual     「실제로는」의 걸음. lifts 는 그 걸음에서 저울을 떠나는 추, seal 은 도장.
