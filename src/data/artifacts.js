export const ARTIFACT_BY_ID = new Map(ARTIFACTS.map(a => [a.id, a]))

export function artifactById(id) {
  return ARTIFACT_BY_ID.get(id) ?? null
}

// 그 막까지 붙는 줄만 남긴다 — 척화비의 「뒤의 넉 자는 당신이 직접 썼다」는 2막부터,
// 「뽑혀 땅에 묻혔다」는 4막부터 참이다. actIndex 는 0부터 세는 자리다.
export function artifactLines(artifact, actIndex = 0) {
  return (artifact?.lines ?? [])
    .map(l => (typeof l === 'string' ? { text: l, whenAct: 0 } : l))
    .filter(l => (l.whenAct ?? 0) <= actIndex + 1)
    .map(l => l.text)
}

