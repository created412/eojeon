// ── 적는 법 ───────────────────────────────────────────────────────────────
//
//   rows   [{ year, text }] — text 안의 {낱말} 이 빈칸이다. 조사는 중괄호 밖에 둔다.
//   extra  빈칸에 들어가지 않는 낱말. 같은 쪽에 나오는, 헷갈릴 만한 것을 둔다 —
//          낱말 수와 빈칸 수가 같으면 마지막 칸은 읽지 않고도 찬다.
//   ahead  이 막에서 무엇을 하게 되는지 한 줄.
//
// ⚠ 빈칸의 낱말이 **다른 줄에 그대로 적혀 있으면 안 된다** — 읽지 않고 베껴 채울 수 있다.
//   시험(tests/ui/act-background.test.js)이 다섯 막을 모두 훑는다.
//
// ── 사진 ──────────────────────────────────────────────────────────────────
//
// 선생님(2026-10-06): 「여기에 기존에 있던 사진이나 그림들 어디 갔어? 포함해서 다시 한 판에
// 들어오게 만들어. 다른 막들도 마찬가지야.」
//
// 연표로 갈면서 사진을 뺐었다(캡션이 화면을 길게 만든다는 까닭이었다). 되살린다 — 줄마다
// 오른쪽에 작은 사진 한 장이 서고, 누르면 크게 뜬다. 한 판에 들어오는 것은 그대로다.
//
//   media     ui/historical-media-data.js 의 열쇠. **이미 게임 안에 실린 사진·초상만** 쓴다.
//             새 그림을 만들지 않는다 — 배경지식을 설명하는 자리에 필요한 것은 진짜 자료다.
//   relation  그 사진이 이 줄과 어떤 사이인가. **반드시 적는다.** 사진이 그 장면을 찍은 것이
//             아닐 때(고종의 초상은 즉위 때가 아니고, 근정전 사진은 중건 직후가 아니다)
//             그 사실을 이 줄이 먼저 말한다. 화면이 이 줄을 빠뜨릴 수 없게 시험이 붙든다.
//   알맞은 자료가 없는 줄에는 사진을 두지 않는다(억지로 채우지 않는다).
//
