// 눌러 채운다(ui/act-background.js · systems/cloze.js). 한 화면에 들어오고, 문장을
// 읽어야 채울 수 있다.
//
// ── 글의 근거 ─────────────────────────────────────────────────────────────
//
// 문장은 **동아출판 『고등 한국사1』(2022 개정)** 의 것이다(막마다 origin 에 쪽수를
