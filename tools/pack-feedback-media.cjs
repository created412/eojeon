const fs = require('node:fs'), path = require('node:path'), os = require('node:os');
const sharp = require(path.join(os.homedir(), '.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/sharp'));
const base = path.join(os.homedir(), 'AppData/Roaming/orca/codex-runtime-home/home/generated_images/01a097ea-8164-7322-9276-fbddd9cf1b12');
const files = {
  sack: 'exec-3629f990-c287-4d2a-b55d-63c294b5f329.png',
  grain: 'exec-b3cd7d45-db55-4f3a-a8ce-8d0ced6cf852.png',
  mother: 'exec-10037b68-84fd-4462-8351-b63f488fdb95.png',
};
(async () => {
  const out = 'assets/feedback'; fs.mkdirSync(out, { recursive: true });
  const media = {};
  for (const [key, filename] of Object.entries(files)) {
    const original = path.join(out, key + '.png');
    if (!fs.existsSync(original)) fs.copyFileSync(path.join(base, filename), original);
    const webp = await sharp(original).resize({ width: 820, withoutEnlargement: true }).webp({ quality: 76 }).toBuffer();
    fs.writeFileSync(path.join(out, key + '.webp'), webp);
    media[key] = 'data:image/webp;base64,' + webp.toString('base64');
    console.log(key, Math.round(webp.length / 1024), 'KB');
  }
  fs.writeFileSync('src/ui/feedback-media-data.js', '// Generated by tools/pack-feedback-media.cjs. AI reconstruction artwork.\nexport const FEEDBACK_MEDIA = ' + JSON.stringify(media) + '\n');
})();
