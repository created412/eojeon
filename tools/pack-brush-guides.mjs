import { createRequire } from 'node:module'
import { homedir } from 'node:os'
import { join } from 'node:path'
import { writeFileSync } from 'node:fs'
const require = createRequire(import.meta.url)
let pw
try { pw = require('playwright') } catch {
  pw = require(join(homedir(), '.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright'))
}

// 2026-10-06 선생님: 「주화매국 쓸때 나라국자의 윗변 따라쓰는란이 없네」.
// 홀수 좌표 한 점만 검사하면 짝수 줄에 놓인 얇은 가로획이 통째로 빠졌다.
// 2×2 칸 전체에서 가장 짙은 실제 획을 고른다. 글꼴의 획을 임의로 추가하지 않는다.
const browser = await pw.chromium.launch({ channel: 'chrome', headless: true })
try {
  const page = await browser.newPage()
  const guides = await page.evaluate(() => {
    const out = {}
    for (const ch of new Set('洋夷侵犯非戰則和主和賣國日使來衛')) {
      const c = document.createElement('canvas')
      c.width = c.height = 96
      const g = c.getContext('2d', { willReadFrequently: true })
      g.fillStyle = 'white'; g.fillRect(0, 0, 96, 96)
      g.fillStyle = 'black'; g.font = '79px Batang, SimSun, serif'
      g.textAlign = 'center'; g.textBaseline = 'middle'; g.fillText(ch, 48, 52)
      const pixels = g.getImageData(0, 0, 96, 96).data
      const pts = []
      for (let y = 2; y < 94; y += 2) for (let x = 2; x < 94; x += 2) {
        let darkest = 128, point = null
        for (let dy = 0; dy < 2; dy++) for (let dx = 0; dx < 2; dx++) {
          const value = pixels[((y + dy) * 96 + x + dx) * 4]
          if (value < darkest) { darkest = value; point = { x: +( (x + dx) / 96).toFixed(5), y: +((y + dy) / 96).toFixed(5) } }
        }
        if (point) pts.push(point)
      }
      out[ch] = pts
    }
    return out
  })
  writeFileSync('src/ui/brush-guides-data.js', '// Generated by tools/pack-brush-guides.mjs. Every 2x2 pixel cell is inspected; thin strokes are preserved.\nexport const BRUSH_GUIDES=' + JSON.stringify(guides) + '\n')
  console.log(Object.fromEntries(Object.entries(guides).map(([ch, pts]) => [ch, pts.length])))
} finally { await browser.close() }
